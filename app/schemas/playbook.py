"""Playbooks as typed DAGs (paper Section V).

A playbook is a DAG whose nodes are actions from the controlled vocabulary and whose edges
carry a typed artifact: an edge u -> v (artifact t) means output t of u satisfies input t of v.
These models describe *structure only*; validity against the vocabulary (acyclic, inputs met,
types agree, no orphans, terminal action, verification before destructive actions, node cap)
is checked by :mod:`app.playbook.validator`.
"""

from __future__ import annotations

import hashlib
import json
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field

from app.schemas.enums import EvidenceCategory
from app.schemas.incident import INTENT_LABEL_PATTERN

NODE_ID_PATTERN = r"^[A-Za-z0-9_-]{1,40}$"
ACTION_ID_PATTERN = r"^[a-z][a-z0-9_]{0,63}$"
MAX_PARSED_NODES = 60  # parsing bound for untrusted input; the validity cap (paper: 20) is enforced by the validator


class Phase(str, Enum):
    """Response phases in the order a sound playbook usually visits them (used for sequencing checks)."""

    TRIAGE = "triage"
    ENRICHMENT = "enrichment"
    INVESTIGATION = "investigation"
    SCOPING = "scoping"
    VERIFICATION = "verification"
    CONTAINMENT = "containment"
    ERADICATION = "eradication"
    RECOVERY = "recovery"
    REPORTING = "reporting"

    @property
    def order(self) -> int:
        return list(Phase).index(self)


class PlaybookOrigin(str, Enum):
    SEED = "seed"  # hand-authored playbook shipped with CADE
    IMPORTED = "imported"  # added by a library administrator
    LLM = "llm"  # generated by the language model (after repair)
    CONSTRUCTIVE = "constructive"  # built by CADE's goal-driven constructive generator
    EVOLVED = "evolved"  # produced by the CADE evolutionary search


class PlaybookNode(BaseModel):
    model_config = ConfigDict(extra="forbid")

    node_id: str = Field(pattern=NODE_ID_PATTERN)
    action: str = Field(pattern=ACTION_ID_PATTERN)
    params: dict[str, Any] = Field(default_factory=dict)


class PlaybookEdge(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    source: str = Field(pattern=NODE_ID_PATTERN)
    target: str = Field(pattern=NODE_ID_PATTERN)
    artifact: str = Field(pattern=r"^[a-z][a-z0-9_]{0,63}$")


class Playbook(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1, max_length=200)
    intent_label: str = Field(pattern=INTENT_LABEL_PATTERN)
    description: Optional[str] = Field(default=None, max_length=2000)
    origin: PlaybookOrigin
    nodes: list[PlaybookNode] = Field(min_length=1, max_length=MAX_PARSED_NODES)
    edges: list[PlaybookEdge] = Field(default_factory=list, max_length=MAX_PARSED_NODES * 8)

    def node(self, node_id: str) -> Optional[PlaybookNode]:
        return next((n for n in self.nodes if n.node_id == node_id), None)

    def structural_hash(self) -> str:
        """Identity of the graph's structure, independent of node IDs, names and list order.

        Each node is labelled by its action, parameters and (recursively) the labels feeding it,
        so isomorphic DAGs with the same actions hash equally while different wirings do not.
        """
        incoming: dict[str, list[PlaybookEdge]] = {n.node_id: [] for n in self.nodes}
        for edge in self.edges:
            incoming.setdefault(edge.target, []).append(edge)
        base = {n.node_id: f"{n.action}{json.dumps(n.params, sort_keys=True, default=str)}" for n in self.nodes}
        labels: dict[str, str] = {}

        def label(node_id: str, depth: int = 0) -> str:
            if node_id in labels:
                return labels[node_id]
            if depth > len(self.nodes):  # cycle guard: fall back to the local label
                return base.get(node_id, node_id)
            parents = sorted(f"{e.artifact}<{label(e.source, depth + 1)}" for e in incoming.get(node_id, []))
            labels[node_id] = hashlib.sha256((base.get(node_id, node_id) + "|" + ";".join(parents)).encode()).hexdigest()
            return labels[node_id]

        signature = sorted(label(n.node_id) for n in self.nodes)
        return hashlib.sha256(json.dumps(signature).encode()).hexdigest()

    def action_multiset(self) -> list[str]:
        return sorted(n.action for n in self.nodes)


class RequiredEvidence(BaseModel):
    """The evidence a playbook needs (paper Eq. 1: critical R_c and supporting R_s)."""

    critical: list[EvidenceCategory] = Field(default_factory=list)
    supporting: list[EvidenceCategory] = Field(default_factory=list)
